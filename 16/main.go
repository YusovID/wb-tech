package main

import "fmt"

func main() {
	nums := []int{5, 4, 3, 2, 1}
	fmt.Println(nums)

	// начальные границы для сортировки всего среза
	l, r := 0, len(nums)-1

	quickSort(nums, l, r)
	fmt.Println(nums)
}

// quickSort - рекурсивная функция сортировки
func quickSort(nums []int, l, r int) {
	// базовый случай рекурсии: в срезе 1 или 0 элементов
	if l < r {
		// p - индекс, по которому массив разделен
		p := partition(nums, l, r)

		// рекурсивно сортируем левую часть
		quickSort(nums, l, p)
		// рекурсивно сортируем правую часть
		quickSort(nums, p+1, r)
	}
}

// partition - разделяет срез на две части относительно опорного элемента
func partition(nums []int, l, r int) int {
	// выбираем опорный элемент по центру
	mid := l + (r-l)/2
	pivot := nums[mid]

	// бесконечный цикл, прерывается изнутри
	for {
		// ищем слева элемент, который больше или равен опорному
		for nums[l] < pivot {
			l++
		}
		// ищем справа элемент, который меньше или равен опорному
		for nums[r] > pivot {
			r--
		}

		// если указатели встретились или пересеклись, разделение закончено
		if l >= r {
			// возвращаем r как границу левой части
			return r
		}

		// меняем элементы местами
		nums[l], nums[r] = nums[r], nums[l]
		// сдвигаем указатели, чтобы избежать зацикливания на равных элементах
		l++
		r--
	}
}
